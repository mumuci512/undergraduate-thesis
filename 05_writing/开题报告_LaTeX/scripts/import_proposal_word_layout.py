"""Import the fixed labels of the Word form as editable TeX glyph runs.

Only fixed form text and rules are imported. Research text, metadata and opinions
remain normal editable LaTeX content; no PDF page is used as a background.
"""
import argparse,json
from pathlib import Path
import pdfplumber

parser=argparse.ArgumentParser()
parser.add_argument('reference',type=Path)
parser.add_argument('--out',type=Path,default=Path('style/tongji-proposal-word-text.def'))
args=parser.parse_args()
def esc(s):
    return ''.join({'\\':r'\textbackslash{}','{':r'\{','}':r'\}','%':r'\%','&':r'\&','#':r'\#','_':r'\_','$':r'\$','^':r'\textasciicircum{}','~':r'\textasciitilde{}'}.get(c,c) for c in s)
names=[['cover_title','cover_topic','cover_subtitle','cover_school','cover_major','cover_student','cover_date'],
       ['heading1','guide1','guide2','guide3','note','source','state','heading2','research','method1','method2','schedule','references','review'],
       ['teacher_label','teacher_hint1','teacher_hint2','teacher_sign','teacher_date','department_label','department_hint','department_sign','department_date']]
result=['% Fixed Word form labels as selectable, editable TeX text. Generated by scripts/import_proposal_word_layout.py.']
mapping=[]
with pdfplumber.open(args.reference) as pdf:
    for page,nms in zip(pdf.pages,names):
        lines=page.extract_text_lines()
        assert len(lines)==len(nms),(len(lines),len(nms))
        for name,line in zip(nms,lines):
            chars=[c for c in line['chars'] if c['text'].strip()]
            left=chars[0]['x0']; baseline=page.height-chars[0]['matrix'][5]
            glyphs=[]
            for c in chars:
                family=c['fontname'].split('+')[-1]
                font='hei' if 'SimHei' in family else ('roman' if 'Times' in family else 'song')
                grey=c['non_stroking_color']
                grey=grey[0] if isinstance(grey,(list,tuple)) else grey
                cb=page.height-c['matrix'][5]
                glyphs.append(r'\tjword@glyph{%.5f}{%.5f}{%s}{%.5f}{%.5f}{%s}'%(c['x0']-left,baseline-cb,font,c['size'],grey,esc(c['text'])))
            # Signature/date underlines are graphics in Word, not underscore characters.
            if name.endswith('_sign') or name.endswith('_date'):
                for r in page.rects:
                    if 0<r['height']<1 and r['width']<100 and baseline<=r['top']<baseline+5:
                        glyphs.append(r'\tjword@inlinerule{%.5f}{%.5f}{%.5f}{%.5f}'%(r['x0']-left,baseline-r['bottom'],r['width'],r['height']))
            result.append(r'\expandafter\def\csname tjword@static@%s\endcsname{\hbox to %.5fbp{%%'%(name,line['x1']-left))
            result += [g+'%' for g in glyphs] + [r'\hfil}}']
            if name in ['heading1','source','state','heading2','research','schedule','references','review','note','teacher_label','department_label','department_hint']:
                mapping.append((line['text'].replace(' ',''),name))
        if page.page_number==1:
            result.append(r'\def\tjword@coverrules{%')
            for r in page.rects:
                if 0<r['height']<1 and r['width']>0:
                    result.append(r'\tjword@at{%.5f}{%.5f}{\rule{%.5fbp}{%.5fbp}}%%'%(r['x0'],r['bottom'],r['width'],r['height']))
            result.append('}')
result += [r'\expandafter\def\csname tjword@static@method\endcsname{\TJWordStatic{method1}\linebreak\TJWordStatic{method2}}',r'\ExplSyntaxOn',r'\prop_new:N \g_tjword_static_prop']
mapping.append(('2．研究方案（包括但不限于拟采取的研究方法、技术路线图、可行性分析等）','method'))
for text,name in mapping:
    result.append(r'\prop_gput:Nnn \g_tjword_static_prop {%s} {%s}'%(esc(text),name))
result += [r'\cs_new_protected:Npn \TJWordKnown #1 {',r'  \prop_get:NnNTF \g_tjword_static_prop {#1} \l_tmpa_tl',r'    {\exp_args:NV \TJWordStatic \l_tmpa_tl} {#1}',r'}',r'\ExplSyntaxOff']
args.out.write_text('\n'.join(result)+'\n',encoding='utf-8')
